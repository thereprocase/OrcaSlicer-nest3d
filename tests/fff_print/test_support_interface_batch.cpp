// Every extrusion sits beside material at most `lead` taller than the nozzle, and no travel passes
// through material taller than the nozzle.
void check_nozzle_clearance(const Parsed &batched)
{
    HeightMap printed;
    int       extrusions_checked = 0, travels_checked = 0, batch_travels = 0;
    double    deepest = -1., lowest_clearance = 1.;
    for (const Move &m : batched.moves) {
        if (m.extrudes) {
            // An extrusion may sit next to material at most `lead` taller than the nozzle.
            deepest = std::max(deepest, printed.max_near(m, 1.0) - m.to.z());
            ++extrusions_checked;
            printed.deposit(m);
        } else {
            // A travel never passes through material taller than the nozzle at either end.
            const double z = std::min(m.from.z(), m.to.z());
            lowest_clearance = std::min(lowest_clearance, z - printed.max_near(m, 0.25));
            ++travels_checked;
            batch_travels += m.in_batch;
        }
    }
    CHECK(extrusions_checked > 0);
    CHECK(batch_travels > 0);
    CHECK(deepest <= lead + eps);
    CHECK(lowest_clearance >= -eps);
}

// Interface line samples that print over nothing printed before them (no material within 0.3 mm
// below), and those with material printed before them standing over them.
std::pair<int, int> unsupported_interface(const Parsed &parsed)
{
    HeightMap printed;
    int       floating = 0, covered = 0;
    for (const Move &m : parsed.moves) {
        if (!m.extrudes)
            continue;
        if (m.interface) {
            Move point = m;
            const Vec2d a = m.from.head<2>(), b = m.to.head<2>();
            const size_t n = std::max<size_t>(1, size_t(std::ceil((b - a).norm() / 0.2)));
            for (size_t i = 0; i <= n; ++i) {
                const Vec2d p = a + (b - a) * (double(i) / n);
                point.from = Vec3d(p.x(), p.y(), m.to.z());
                point.to   = point.from;
                const double below = printed.max_near(point, 0.3);
                floating += below < m.to.z() - 0.3;
                covered  += printed.max_near(point, 0.05) > m.to.z() + eps;
            }
        }
        printed.deposit(m);
    }
    return { floating, covered };
}

