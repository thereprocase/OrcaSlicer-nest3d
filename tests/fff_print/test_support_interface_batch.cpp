constexpr double layer_height = 0.2;
constexpr double lead         = 0.4;
constexpr double eps          = 1e-3;

// A 10 mm pillar under a 30 x 10 mm cap from z = 6 to 8: the cap overhangs 10 mm on both sides,
// so normal supports reach up to z = 6 under it.
TriangleMesh capped_pillar()
{
    TriangleMesh mesh = make_cube(10, 10, 6);
    TriangleMesh cap  = make_cube(30, 10, 2);
    cap.translate(-10, 0, 6);
    mesh.merge(cap);
    return mesh;
}

// Object in filament 1, support base in "any" filament, interface in filament 2 that the base may
// not use. Five top interface layers with a separate interface filament print the lowest of them
// in the base filament, so each support column carries four interface layers of filament 2:
// two round trips stock, one batched with a 0.4 mm lead at 0.2 mm layers.
DynamicPrintConfig batch_config(bool batch)
{
    return multifilament_config(2, {
        { "layer_height",                   layer_height },
        { "initial_layer_print_height",     layer_height },
        { "enable_support",                 1 },
        { "support_type",                   "normal(auto)" },
        { "support_filament",               0 },
        { "support_interface_filament",     2 },
        { "support_interface_not_for_body", 1 },
        { "support_interface_top_layers",   5 },
        { "support_interface_bottom_layers", 0 },
        { "support_top_z_distance",         0 },
        { "support_object_xy_distance",     1 },
        { "enable_prime_tower",             1 },
        { "wipe_tower_type",                "type1" },
        { "wipe_tower_x",                   150 },
        { "wipe_tower_y",                   150 },
        { "z_hop",                          0.4 },
        { "support_interface_batch",        batch ? 1 : 0 },
        { "support_interface_batch_lead",   lead },
    });
}

// Slices the capped pillar. The second apply keeps the prime tower: a new Print's first apply
// sees one filament in use and normalize_fdm_2 drops the tower (see test_wipe_tower.cpp).
std::string slice(Print &print, const DynamicPrintConfig &config)
{
    Model model;
    init_print({ capped_pillar() }, print, model, config);
    print.apply(model, config);
    return gcode(print);
}

std::string slice(const DynamicPrintConfig &config)
{
    Print print;
    return slice(print, config);
}

// The G-code without its "; generated by ... on <time>" header line and the config dump, which
// records the batching option itself.
std::string without_timestamp_and_config(std::string gcode)
{
    const size_t start = gcode.find("; generated by ");
    if (start != std::string::npos)
        gcode.erase(start, gcode.find('\n', start) - start);
    const size_t config = gcode.find("; CONFIG_BLOCK_START");
    if (config != std::string::npos)
        gcode.erase(config);
    return gcode;
}

struct Move
{
    Vec3d from;
    Vec3d to;
    bool  extrudes;
    bool  interface;
    bool  in_batch;
};

struct Batch
{
    std::vector<double> layer_z;          // BATCHED_INTERFACE_LAYER values, in order
    std::vector<double> interface_z;      // Z of every interface extrusion inside the block, in order
    double              printed_before = 0.; // tallest extrusion before the block
};

struct Parsed
{
    std::vector<Move>  moves;
    std::vector<Batch> batches;
    int                loads_of_interface = 0; // tool changes to the interface filament (T1)
    int                tool_changes       = 0;
    int                interface_outside_batches = 0;
    // Extrusions outside the batch blocks that are not at their layer's Z.
    int                off_layer_extrusions = 0;
};

Parsed parse(const std::string &gcode)
{
    Parsed       out;
    GCodeReader  reader;
    bool         printing   = false; // past the first layer change
    bool         interface  = false;
    bool         in_batch   = false;
    int          tool       = -1;
    double       printed_z  = 0.;
    double       layer_z    = 0.;
    reader.parse_buffer(gcode, [&](GCodeReader &r, const GCodeReader::GCodeLine &line) {
        const std::string_view raw = line.raw();
        if (raw.rfind(";LAYER_CHANGE", 0) == 0 || raw.rfind("; CHANGE_LAYER", 0) == 0)
            printing = true;
        else if (raw.rfind(";Z:", 0) == 0)
            layer_z = std::stod(std::string(raw.substr(3)));
        else if (raw.rfind("; Z_HEIGHT: ", 0) == 0)
            layer_z = std::stod(std::string(raw.substr(12)));
        else if (raw.rfind(";TYPE:", 0) == 0)
            interface = raw.substr(6) == "Support interface";
        else if (raw.rfind("; FEATURE: ", 0) == 0)
            interface = raw.substr(11) == "Support interface";
        else if (raw.rfind("; BATCHED_INTERFACE_START", 0) == 0) {
            in_batch = true;
            out.batches.push_back({});
            out.batches.back().printed_before = printed_z;
        } else if (raw.rfind("; BATCHED_INTERFACE_END", 0) == 0)
            in_batch = false;
        else if (raw.rfind("; BATCHED_INTERFACE_LAYER: ", 0) == 0)
            out.batches.back().layer_z.push_back(std::stod(std::string(raw.substr(27))));
        else if (raw.size() >= 2 && raw[0] == 'T' && std::isdigit((unsigned char) raw[1])) {
            const int t = std::stoi(std::string(raw.substr(1)));
            if (printing && t != tool) {
                ++out.tool_changes;
                if (t == 1)
                    ++out.loads_of_interface;
            }
            tool = t;
        } else if (printing && (line.cmd_is("G1") || line.cmd_is("G0"))) {
            const Vec3d from(r.x(), r.y(), r.z());
            const Vec3d to(line.new_X(r), line.new_Y(r), line.new_Z(r));
            const bool  extrudes = line.extruding(r) && line.dist_XY(r) > 0.f;
            if (extrudes || line.travel())
                out.moves.push_back({ from, to, extrudes, extrudes && interface, in_batch });
            if (extrudes) {
                printed_z = std::max(printed_z, to.z());
                if (!in_batch && std::abs(to.z() - layer_z) > eps)
                    ++out.off_layer_extrusions;
                if (interface && in_batch)
                    out.batches.back().interface_z.push_back(to.z());
                else if (interface)
                    ++out.interface_outside_batches;
            }
        }
    });
    return out;
}

// Tallest extruded material per 0.2 mm cell, filled in print order.
class HeightMap
{
public:
    void deposit(const Move &m)
    {
        for_samples(m, [this, &m](const Vec2d &p) {
            double &h = m_cells[key(cell(p.x()), cell(p.y()))];
            h         = std::max(h, m.to.z());
        });
    }
    // Tallest material within `radius` of the move's path, 0 if none.
    double max_near(const Move &m, double radius) const
    {
        double     top = 0.;
        const long r   = long(std::ceil(radius / cell_size));
        for_samples(m, [&](const Vec2d &p) {
            const long cx = cell(p.x()), cy = cell(p.y());
            for (long ix = cx - r; ix <= cx + r; ++ix)
                for (long iy = cy - r; iy <= cy + r; ++iy) {
                    auto it = m_cells.find(key(ix, iy));
                    if (it == m_cells.end())
                        continue;
                    const double dx = std::max({ ix * cell_size - p.x(), 0., p.x() - (ix + 1) * cell_size });
                    const double dy = std::max({ iy * cell_size - p.y(), 0., p.y() - (iy + 1) * cell_size });
                    if (dx * dx + dy * dy <= radius * radius)
                        top = std::max(top, it->second);
                }
        });
        return top;
    }

private:
    static constexpr double cell_size = 0.2;
    static long     cell(double v) { return long(std::floor(v / cell_size)); }
    static int64_t  key(long x, long y) { return (int64_t(x) << 32) ^ int64_t(uint32_t(y)); }
    template<class F> static void for_samples(const Move &m, F f)
    {
        const Vec2d  a = m.from.head<2>(), b = m.to.head<2>();
        const size_t n = std::max<size_t>(1, size_t(std::ceil((b - a).norm() / 0.1)));
        for (size_t i = 0; i <= n; ++i)
            f(a + (b - a) * (double(i) / n));
    }
    std::unordered_map<int64_t, double> m_cells;
};

